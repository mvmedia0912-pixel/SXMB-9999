import { XSMBDraw } from '../types/lottery.ts';

// Province schedule by day of week (0 = Sunday, 1 = Monday, ..., 6 = Saturday)
export const PROVINCE_SCHEDULE: Record<number, { name: string; day: string }> = {
  0: { name: 'Thái Bình', day: 'Chủ Nhật' },
  1: { name: 'Hà Nội', day: 'Thứ Hai' },
  2: { name: 'Quảng Ninh', day: 'Thứ Ba' },
  3: { name: 'Bắc Ninh', day: 'Thứ Tư' },
  4: { name: 'Hà Nội', day: 'Thứ Năm' },
  5: { name: 'Hải Phòng', day: 'Thứ Sáu' },
  6: { name: 'Nam Định', day: 'Thứ Bảy' },
};

export function extractPrizesFlat(prizes: XSMBDraw['prizes']): string[] {
  return [
    prizes.db,
    prizes.g1,
    ...prizes.g2,
    ...prizes.g3,
    ...prizes.g4,
    ...prizes.g5,
    ...prizes.g6,
    ...prizes.g7,
  ];
}

export function extractLoTo2D(flatPrizes: string[]): string[] {
  return flatPrizes.map((p) => p.slice(-2));
}

export function createDraw(
  date: string,
  db: string,
  g1: string,
  g2: [string, string],
  g3: [string, string, string, string, string, string],
  g4: [string, string, string, string],
  g5: [string, string, string, string, string, string],
  g6: [string, string, string],
  g7: [string, string, string, string]
): XSMBDraw {
  const d = new Date(date + 'T18:15:00+07:00');
  const dow = d.getDay();
  const sched = PROVINCE_SCHEDULE[dow] || { name: 'Hà Nội', day: 'Thứ Hai' };

  const prizes = {
    db,
    g1,
    g2,
    g3,
    g4,
    g5,
    g6,
    g7,
  };

  const allPrizesList = extractPrizesFlat(prizes);
  const loTo2D = extractLoTo2D(allPrizesList);

  return {
    id: `xsmb-${date}`,
    date,
    dayOfWeek: sched.day,
    province: sched.name,
    prizes,
    allPrizesList,
    loTo2D,
    de2D: db.slice(-2),
    de3D: db.slice(-3),
  };
}

